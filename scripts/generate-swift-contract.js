#!/usr/bin/env node
// Generates AnalysisContract.generated.swift from shared/analysis-contract.json.
// Run after editing the contract: `npm run contract` (tests fail while the Swift file is stale).
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const CONTRACT_PATH = path.join(ROOT, "shared", "analysis-contract.json");
const SWIFT_PATH = path.join(
  ROOT,
  "macos-native",
  "Sources",
  "InterviewHelperCore",
  "AnalysisContract.generated.swift",
);

function swiftString(text) {
  const escaped = text
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r")
    .replace(/\t/g, "\\t")
    .replace(/[\u0000-\u001f]/g, (c) => `\\u{${c.charCodeAt(0).toString(16)}}`);
  return `"${escaped}"`;
}

function swiftStringArray(items, indent) {
  return `[\n${items.map((item) => `${indent}    ${swiftString(item)},`).join("\n")}\n${indent}]`;
}

function swiftField(field) {
  const allowed = field.enum ? swiftStringArray(field.enum, "            ") : "[]";
  return `        AnalysisField(\n            key: ${swiftString(field.key)},\n            description: ${swiftString(field.description)},\n            allowedValues: ${allowed}\n        ),`;
}

function renderSwift(contract) {
  return `// GENERATED by scripts/generate-swift-contract.js from shared/analysis-contract.json — do not edit.

struct AnalysisField: Sendable, Equatable {
    let key: String
    let description: String
    /// Empty means free text.
    let allowedValues: [String]
}

enum AnalysisContract {
    static let defaultModel = ${swiftString(contract.defaultModel)}

    /// Former defaults that Settings saved verbatim; treated as "use the current default".
    static let retiredDefaultModels: Set<String> = ${swiftStringArray(contract.retiredDefaultModels, "    ")}

    static let systemPrompt = ${swiftString(contract.systemPrompt)}

    static let defaultAnalyzePrompt = ${swiftString(contract.defaultAnalyzePrompt.join("\n"))}

    static let improveSystemPrompt = ${swiftString(contract.improveSystemPrompt)}

    static let improveInstructions = ${swiftString(contract.improveInstructions.join("\n"))}

    static let explainSystemPrompt = ${swiftString(contract.explainSystemPrompt)}

    static let explainInstructions = ${swiftString(contract.explainInstructions.join("\n"))}

    /// Fields of the current answer given to the model as context for improve / explain.
    static let solutionContextKeys = ${swiftStringArray(contract.solutionContextKeys, "    ")}

    static let fields = [
${contract.fields.map(swiftField).join("\n")}
    ]
}
`;
}

function loadContract() {
  return JSON.parse(fs.readFileSync(CONTRACT_PATH, "utf8"));
}

module.exports = { SWIFT_PATH, loadContract, renderSwift };

if (require.main === module) {
  fs.writeFileSync(SWIFT_PATH, renderSwift(loadContract()));
  console.log(`Wrote ${path.relative(ROOT, SWIFT_PATH)}`);
}
